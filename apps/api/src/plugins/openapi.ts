import fp from 'fastify-plugin'
import type { FastifyInstance } from 'fastify'
import swagger from '@fastify/swagger'
import { ROUTE_DOCS } from '@/api-docs/catalog'
import { toRouteSchema } from '@/lib/api-doc'

// API documentation (OpenAPI 3.1) collected from every route. Summaries, bodies and queries come
// from the catalog (src/api-docs), applied here at documentation time only: routes carry no
// Fastify schema, so validation stays with the handler's Zod parsing.
// The reference page (Scalar) exists only with API_DOCS_ENABLED=true outside production; the spec file and the llms text are
// generated by `pnpm --filter api docs:api`.

// @fastify/helmet reads per-route options from `config.helmet` at request time
declare module 'fastify' {
  interface FastifyContextConfig {
    helmet?: { contentSecurityPolicy?: false }
  }
}

// Module of each first path segment, as the office calls it
const TAG_BY_SEGMENT: Record<string, string> = {
  auth: 'Autenticação', master: 'Master (AutoHubs)', organizations: 'Cadastro público', org: 'Organização',
  webhooks: 'Webhooks', users: 'Usuários', clients: 'Clientes', boards: 'Processos', columns: 'Tarefas',
  tasks: 'Tarefas', comments: 'Comentários', notifications: 'Notificações', portal: 'Portal do cliente',
  stream: 'Tempo real', requests: 'Solicitações', 'request-comments': 'Solicitações', protocols: 'Protocolos',
  dashboard: 'Dashboard', departments: 'Departamentos', holidays: 'Feriados', 'os-models': 'Modelos de OS',
  os: 'Ordens de Serviço', 'delay-reasons': 'Motivos de atraso', 'recurring-templates': 'Tarefas recorrentes',
  'client-users': 'Usuários do portal', 'process-templates': 'Modelos de processo', sla: 'SLA',
  'document-reader': 'Robô de documentos', municipalities: 'Municípios', approvals: 'Aprovações', health: 'Sistema',
}

// Routes that do not take the bearer token
const PUBLIC = new Set(['/auth/login', '/auth/refresh', '/auth/logout', '/organizations/plans', '/organizations/signup-status', '/organizations/register', '/health'])

function tagFor(url: string): string {
  const segment = url.split('/')[1] ?? ''
  return TAG_BY_SEGMENT[segment] ?? 'Outros'
}

function securityFor(url: string, method: string): Record<string, string[]>[] {
  if (PUBLIC.has(url)) return []
  if (url.startsWith('/webhooks/')) return [{ asaasToken: [] }]
  if (method === 'GET' && url.endsWith('/stream')) return [{ streamTicket: [] }]
  return [{ bearerAuth: [] }]
}

function catalogSchema(method: string, url: string): Record<string, unknown> {
  const entry = ROUTE_DOCS[`${method} ${url}`]
  return entry ? toRouteSchema(entry) : {}
}

export default fp(async function openapi(app: FastifyInstance) {
  await app.register(swagger, {
    openapi: {
      openapi: '3.1.0',
      info: {
        title: 'Tramita API',
        version: '1.0.0',
        description:
          'API do Tramita (AutoHubs): processos, ordens de serviço, tarefas e portal do cliente de escritórios contábeis. ' +
          'Toda rota privada usa `Authorization: Bearer <accessToken>` (JWT RS256, 15 min; renove em POST /auth/refresh). ' +
          'Erros sempre como `{ "message": "..." }` em pt-BR. Multi-tenant: tudo é filtrado pela organização do token.',
      },
      // Only the local API here, so "Try it" on the reference never hits production; the generated
      // file (docs:api) swaps in the public address
      servers: [{ url: `http://localhost:${process.env.PORT ?? 3000}`, description: 'Local' }],
      components: {
        securitySchemes: {
          bearerAuth: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' },
          asaasToken: { type: 'apiKey', in: 'header', name: 'asaas-access-token' },
          streamTicket: { type: 'apiKey', in: 'query', name: 'ticket', description: 'Ticket de uso único de POST /stream/ticket (30 s)' },
        },
      },
    },
    transform: ({ schema, url: rawUrl, route }) => {
      const method = Array.isArray(route.method) ? route.method[0] : route.method
      // Fastify registers every prefixed '/' route twice ('/users' and '/users/'): document one
      const url = rawUrl.length > 1 ? rawUrl.replace(/\/$/, '') : rawUrl
      const own = { ...(schema ?? {}), ...catalogSchema(method, url) } as Record<string, unknown>
      // Plumbing, not API: the reference page itself, CORS preflight and the catch-all path
      const hide = url === '/reference' || url.startsWith('/reference/') || method === 'OPTIONS' || url.includes('*')
      return {
        schema: { ...own, hide, tags: (own.tags as string[] | undefined) ?? [tagFor(url)], security: securityFor(url, method) },
        url,
      }
    },
  })

  // Opt-in and never in production: an environment without NODE_ENV (staging, a manual run) does
  // not publish the API map by accident
  if (process.env.API_DOCS_ENABLED === 'true' && process.env.NODE_ENV !== 'production') {
    // Dev dependency: an image built for production (installed with --prod) does not have it
    const reference = await import('@scalar/fastify-api-reference').then((m) => m.default).catch(() => null)
    if (!reference) {
      app.log.warn('API_DOCS_ENABLED=true, mas @scalar/fastify-api-reference não está instalado — /reference não foi publicado')
      return
    }
    await app.register(async (scope) => {
      // The Scalar page boots from an inline script that helmet's CSP blocks. Only this
      // non-production page turns the CSP off (helmet reads `config.helmet` per route); every API
      // route keeps it.
      scope.addHook('onRoute', (routeOptions) => {
        routeOptions.config = { ...(routeOptions.config ?? {}), helmet: { contentSecurityPolicy: false } }
      })
      await scope.register(reference, { routePrefix: '/reference', configuration: { title: 'Tramita API', showDeveloperTools: 'never', agent: { disabled: true } } })
    })
  }
})
